using GitCommitScribe.Models;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading.Tasks;

namespace GitCommitScribe.Rendering
{
    //PR numaralarını (#42) otomatik GitHub linkine dönüştüren, hem yeni sürüm bloğunu üreten hem de mevcut CHANGELOG.md dosyasının en üstüne ekleyen sınıf

    //Ayrıştırılmış commit listesini kategorilere göre gruplayıp Markdown formatına dönüştürür, #123 gibi PR referanslarını otomatik GitHub linkine çevirir ve mevcut CHANGELOG.md dosyasının en üstüne yeni sürüm bloğunu ekler.
    public sealed partial class MarkdownRenderer
    {
        [GeneratedRegex(@"\(#(?<pr>\d+)\)", RegexOptions.Compiled)]
        private static partial Regex PrReferenceRegex();

        private const string MainHeader = "# Changelog\n\nAll notable changes to this project will be documented in this file.\n";
        private const string FooterSignature = "> Generated by [CommitScribe](https://www.nuget.org/packages/CommitScribe)";

        public string RenderVersionSection(
            string versionTitle,
            DateOnly releaseDate,
            IReadOnlyList<ParsedCommit> commits,
            string? repoWebUrl,
            bool includeOther)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"## [{versionTitle}] - {releaseDate:yyyy-MM-dd}");
            sb.AppendLine();

            var orderedCategories = new[]
            {
            (CommitCategory.BreakingChange, "### ⚠️ Breaking Changes"),
            (CommitCategory.Feature, "### ✨ Features"),
            (CommitCategory.BugFix, "### 🐛 Bug Fixes"),
            (CommitCategory.Performance, "### ⚡ Performance Improvements"),
            (CommitCategory.Refactor, "### ♻️ Code Refactoring"),
            (CommitCategory.Documentation, "### 📝 Documentation"),
            (CommitCategory.Other, "### 🔧 Other Changes")
        };

            foreach (var (category, heading) in orderedCategories)
            {
                if (category == CommitCategory.Other && !includeOther)
                    continue;

                var items = commits.Where(c => c.Category == category).ToList();
                if (items.Count == 0)
                    continue;

                sb.AppendLine(heading);
                sb.AppendLine();

                foreach (var item in items)
                {
                    var scopePrefix = !string.IsNullOrWhiteSpace(item.Scope)
                        ? $"**{item.Scope}:** "
                        : string.Empty;

                    var desc = FormatDescriptionWithLinks(item.Description, repoWebUrl);
                    var commitRef = !string.IsNullOrWhiteSpace(repoWebUrl)
                        ? $"([{item.ShortHash}]({repoWebUrl}/commit/{item.Hash}))"
                        : $"({item.ShortHash})";

                    sb.AppendLine($"- {scopePrefix}{desc} {commitRef}");

                    if (item.IsBreaking && !string.IsNullOrWhiteSpace(item.BreakingNote) && item.BreakingNote != item.Description)
                    {
                        sb.AppendLine($"  - **BREAKING:** {item.BreakingNote}");
                    }
                }

                sb.AppendLine();
            }

            return sb.ToString().TrimEnd();
        }

        public string MergeWithExistingFile(string? existingContent, string newVersionSection)
        {
            if (string.IsNullOrWhiteSpace(existingContent))
            {
                return $"{MainHeader}\n{newVersionSection}\n\n---\n{FooterSignature}\n";
            }

            var cleaned = existingContent
                .Replace(FooterSignature, string.Empty)
                .TrimEnd();

            // Eğer dosya "# Changelog" ile başlıyorsa başlığın hemen altına ekle
            var firstSectionIndex = cleaned.IndexOf("\n## ", StringComparison.Ordinal);
            if (firstSectionIndex > 0)
            {
                var headerPart = cleaned[..firstSectionIndex].TrimEnd();
                var olderReleasesPart = cleaned[firstSectionIndex..].TrimStart();
                return $"{headerPart}\n\n{newVersionSection}\n\n{olderReleasesPart}\n\n---\n{FooterSignature}\n";
            }

            return $"{MainHeader}\n{newVersionSection}\n\n{cleaned}\n\n---\n{FooterSignature}\n";
        }

        private static string FormatDescriptionWithLinks(string description, string? repoWebUrl)
        {
            if (string.IsNullOrWhiteSpace(repoWebUrl))
                return description;

            return PrReferenceRegex().Replace(description, match =>
            {
                var pr = match.Groups["pr"].Value;
                return $"([#{pr}]({repoWebUrl}/pull/{pr}))";
            });
        }
    }
}
